#!/usr/bin/env bash
set -euo pipefail

if [[ "${BASH_SOURCE[0]}" != "$0" ]]; then
  echo 'Error: run this script with bash, do not source it.' >&2
  return 1
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
ENV_FILE="${ROOT_DIR}/.env"

usage() {
  cat <<'EOT'
Usage: bgp-udm-config.sh [--members IP[,IP...]]

Prints the FRR configuration for the upstream router (a UniFi gateway's BGP
page takes it as an uploaded/pasted config) from this site's .env, so every
site is built from the same template. The router peers with each Incus member
and accepts only IPv6 prefixes inside IPV6_SUBNET_PREFIX (up to /64); it
announces nothing back and no IPv4 is exchanged. Nothing is applied: it only
prints. If BGP_PASSWORD is set it is part of the output, so don't paste the
output anywhere shared.

Uses BGP_LOCAL_ASN, BGP_PEER_ASN, BGP_PEER_ADDRESS, BGP_PASSWORD and
IPV6_SUBNET_PREFIX from .env. The members' addresses come from the cluster;
with --members they are given instead (run this on a machine without Incus).
EOT
}

MEMBERS_ARG=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --members) [[ $# -ge 2 ]] || { echo 'Error: missing value for --members.' >&2; exit 1; }; MEMBERS_ARG="$2"; shift 2 ;;
    --help|-h) usage; exit 0 ;;
    *) echo "Error: unknown argument: $1" >&2; exit 1 ;;
  esac
done

fail() { echo "Error: $*" >&2; exit 1; }
[[ -f "${ENV_FILE}" ]] || fail "${ENV_FILE} not found."
# shellcheck source=/dev/null
source "${ENV_FILE}"
# shellcheck source=/dev/null
source "${ROOT_DIR}/lib/ipv6.sh"
: "${BGP_LOCAL_ASN:?BGP_LOCAL_ASN not set in ${ENV_FILE}}"
: "${BGP_PEER_ASN:?BGP_PEER_ASN not set in ${ENV_FILE}}"
: "${BGP_PEER_ADDRESS:?BGP_PEER_ADDRESS not set in ${ENV_FILE}}"
[[ "${BGP_LOCAL_ASN}" =~ ^[0-9]+$ && "${BGP_PEER_ASN}" =~ ^[0-9]+$ ]] || fail 'BGP_LOCAL_ASN and BGP_PEER_ASN must be numbers.'
[[ "${BGP_LOCAL_ASN}" != "${BGP_PEER_ASN}" ]] || fail 'BGP_LOCAL_ASN and BGP_PEER_ASN are equal; the sessions are meant to be eBGP (different AS numbers).'
ipv6_enabled || fail 'IPV6_SUBNET_PREFIX is not set in .env.'
ipv6_validate_prefix || exit 1

if [[ -n "${MEMBERS_ARG}" ]]; then
  mapfile -t MEMBER_IPS < <(tr ',' '\n' <<< "${MEMBERS_ARG}")
else
  command -v incus >/dev/null 2>&1 || fail 'incus not found; pass the members with --members.'
  mapfile -t MEMBER_IPS < <(incus query '/1.0/cluster/members?recursion=1' 2>/dev/null \
    | jq -r '.[].url | sub("^https?://"; "") | sub(":[0-9]+$"; "")' 2>/dev/null || true)
  (( ${#MEMBER_IPS[@]} > 0 )) || mapfile -t MEMBER_IPS < <(incus query /1.0 | jq -r '.environment.addresses[0]' | sed -E 's/^\[?([^]]*)\]?:[0-9]+$/\1/')
fi
(( ${#MEMBER_IPS[@]} > 0 )) || fail 'no Incus members found.'

PREFIX="$(python3 -c 'import ipaddress,sys; print(ipaddress.IPv6Network(sys.argv[1]))' "${IPV6_SUBNET_PREFIX}")"

cat <<EOT
! Incus BGP peers - generated by host/bgp-udm-config.sh
! Accepts only IPv6 prefixes inside ${PREFIX} (up to /64) from the Incus members.
ipv6 prefix-list INCUS-V6-IN seq 10 permit ${PREFIX} le 64
!
route-map INCUS-IN permit 10
 match ipv6 address prefix-list INCUS-V6-IN
!
route-map INCUS-OUT deny 10
!
router bgp ${BGP_PEER_ASN}
 bgp router-id ${BGP_PEER_ADDRESS}
 no bgp default ipv4-unicast
 neighbor INCUS peer-group
 neighbor INCUS remote-as ${BGP_LOCAL_ASN}
EOT
[[ -z "${BGP_PASSWORD:-}" ]] || echo " neighbor INCUS password ${BGP_PASSWORD}"
for ip in "${MEMBER_IPS[@]}"; do
  echo " neighbor ${ip} peer-group INCUS"
done
cat <<'EOT'
 !
 address-family ipv6 unicast
  neighbor INCUS activate
  neighbor INCUS route-map INCUS-IN in
  neighbor INCUS route-map INCUS-OUT out
 exit-address-family
exit
EOT
