#!/usr/bin/env bash
set -euo pipefail

if [[ "${BASH_SOURCE[0]}" != "$0" ]]; then
  echo 'Error: run this script with bash, do not source it.' >&2
  return 1
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
ENV_FILE="${ROOT_DIR}/.env"

usage() {
  cat <<'EOT'
Usage: bgp-udm-config.sh [--neighbors IP[,IP...]] [--no-prefix-list]

Prints the FRR configuration for the upstream router (a UniFi gateway's BGP
page takes it as an uploaded/pasted config) from this site's .env, so every
site is built from one template. The router peers with each BGP speaker
(host/bgp-speaker.sh) over the uplink, accepts only IPv6 prefixes inside
IPV6_SUBNET_PREFIX (up to /64), announces nothing back and exchanges no IPv4.
Nothing is applied: it only prints. If BGP_PASSWORD is set it is part of the
output, so don't paste the output anywhere shared.

Uses BGP_LOCAL_ASN, BGP_PEER_ASN, BGP_PEER_ADDRESS (the router's own address on
the uplink, also its router ID), BGP_PASSWORD, BGP_SPEAKERS and
IPV6_SUBNET_PREFIX from .env. The neighbors are the speakers' public IPv4
addresses; --neighbors gives them instead.
--no-prefix-list leaves out the prefix-list filter, for a router page that does
not keep top-level prefix-list lines: every prefix from the speakers is then
accepted, limited to 300 per neighbor.
EOT
}

NEIGHBORS_ARG=''
NO_PREFIX_LIST=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --neighbors) [[ $# -ge 2 ]] || { echo 'Error: missing value for --neighbors.' >&2; exit 1; }; NEIGHBORS_ARG="$2"; shift 2 ;;
    --no-prefix-list) NO_PREFIX_LIST='yes'; shift ;;
    --help|-h) usage; exit 0 ;;
    *) echo "Error: unknown argument: $1" >&2; exit 1 ;;
  esac
done

fail() { echo "Error: $*" >&2; exit 1; }
[[ -f "${ENV_FILE}" ]] || fail "${ENV_FILE} not found."
# shellcheck source=/dev/null
source "${ENV_FILE}"
# shellcheck source=/dev/null
source "${ROOT_DIR}/lib/ipv6.sh"
: "${BGP_LOCAL_ASN:?BGP_LOCAL_ASN not set in ${ENV_FILE}}"
: "${BGP_PEER_ASN:?BGP_PEER_ASN not set in ${ENV_FILE}}"
: "${BGP_PEER_ADDRESS:?BGP_PEER_ADDRESS not set in ${ENV_FILE}}"
[[ "${BGP_LOCAL_ASN}" =~ ^[0-9]+$ && "${BGP_PEER_ASN}" =~ ^[0-9]+$ ]] || fail 'BGP_LOCAL_ASN and BGP_PEER_ASN must be numbers.'
[[ "${BGP_LOCAL_ASN}" != "${BGP_PEER_ASN}" ]] || fail 'BGP_LOCAL_ASN and BGP_PEER_ASN are equal; the sessions are meant to be eBGP (different AS numbers).'
ipv6_enabled || fail 'IPV6_SUBNET_PREFIX is not set in .env.'
ipv6_validate_prefix || exit 1

if [[ -n "${NEIGHBORS_ARG}" ]]; then
  mapfile -t MEMBER_IPS < <(tr ',' '\n' <<< "${NEIGHBORS_ARG}")
else
  : "${BGP_SPEAKERS:?BGP_SPEAKERS not set in ${ENV_FILE} (or pass --neighbors)}"
  command -v incus >/dev/null 2>&1 || fail 'incus not found; pass the neighbors with --neighbors.'
  MEMBER_IPS=()
  for spec in ${BGP_SPEAKERS}; do
    ip="$(incus config get "${spec%@*}" user.public_ipv4 --project "${spec#*@}" 2>/dev/null || true)"
    [[ -n "${ip}" ]] || fail "speaker '${spec}' has no public IPv4 (user.public_ipv4)."
    MEMBER_IPS+=("${ip}")
  done
fi
(( ${#MEMBER_IPS[@]} > 0 )) || fail 'no neighbors.'

PREFIX="$(python3 -c 'import ipaddress,sys; print(ipaddress.IPv6Network(sys.argv[1]))' "${IPV6_SUBNET_PREFIX}")"

if [[ -z "${NO_PREFIX_LIST}" ]]; then
  cat <<EOT
! Incus BGP speakers - generated by host/bgp-udm-config.sh
! Accepts only IPv6 prefixes inside ${PREFIX} (up to /64) from the BGP speakers.
ipv6 prefix-list INCUS-V6-IN seq 10 permit ${PREFIX} le 64
!
route-map INCUS-IN permit 10
 match ipv6 address prefix-list INCUS-V6-IN
!
EOT
else
  cat <<EOT
! Incus BGP speakers - generated by host/bgp-udm-config.sh --no-prefix-list
! Accepts every prefix from the BGP speakers (at most 300 per neighbor).
route-map INCUS-IN permit 10
!
EOT
fi
cat <<EOT
route-map INCUS-OUT deny 10
!
router bgp ${BGP_PEER_ASN}
 bgp router-id ${BGP_PEER_ADDRESS}
 no bgp default ipv4-unicast
 neighbor INCUS peer-group
 neighbor INCUS remote-as ${BGP_LOCAL_ASN}
 neighbor INCUS ebgp-multihop 3
EOT
[[ -z "${BGP_PASSWORD:-}" ]] || echo " neighbor INCUS password ${BGP_PASSWORD}"
for ip in "${MEMBER_IPS[@]}"; do
  echo " neighbor ${ip} peer-group INCUS"
done
echo ' !'
echo ' address-family ipv6 unicast'
echo '  neighbor INCUS activate'
[[ -z "${NO_PREFIX_LIST}" ]] || echo '  neighbor INCUS maximum-prefix 300'
cat <<'EOT'
  neighbor INCUS route-map INCUS-IN in
  neighbor INCUS route-map INCUS-OUT out
 exit-address-family
exit
EOT
